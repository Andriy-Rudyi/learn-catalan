"""Write flaskblog/static/flex-gap.css: margins in place of flex ``gap``.

Browsers before Chrome 84 / Safari 14.1 (old Android tablets, for one)
ignore ``gap`` on flex boxes, so icons stick to their text and buttons to
each other. layout.html marks such a browser with the class
``no-flex-gap`` on <html>; this script finds every rule of main.css and
modern.css that lays out a flex box with a gap and writes the same space
as margins between the children (after each one but the last), only under that class.

Run it after changing a flex gap in those files:

    python scripts/flex_gap_fallback.py

(flaskblog/tests/test_flex_gap.py fails while the file is out of date.)
"""

import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'flaskblog', 'static')
SOURCES = ('main.css', 'modern.css')
OUTPUT = os.path.join(ROOT, 'flex-gap.css')
# The page itself: in the modern design the menu is fixed, out of the flow.
SKIP = ('.lc-page',)
# Gaps next to pseudo-elements, which "> :not(:last-child)" does not reach.
EXTRA = ('html.no-flex-gap[data-design="modern"] .lc-logo::before { margin-right: 10px; }',)

_COMMENT = re.compile(r'/\*.*?\*/', re.S)


def _rules_from(css, start, media):
    """(media, selector, body) for every plain rule; media is '' outside @media."""
    out = []
    media = list(media)
    i = start
    while i < len(css):
        open_at = css.find('{', i)
        close_at = css.find('}', i)
        if close_at == -1:
            break
        if open_at == -1 or close_at < open_at:
            if media:
                media.pop()
            i = close_at + 1
            continue
        head = css[i:open_at].strip()
        if head.startswith('@'):
            media.append(head)
            i = open_at + 1
            continue
        end = css.index('}', open_at)
        out.append((' '.join(media), head, css[open_at + 1:end]))
        i = end + 1
    return out


def _declarations(body):
    found = {}
    for part in body.split(';'):
        if ':' in part:
            name, value = part.split(':', 1)
            found[name.strip().lower()] = value.strip()
    return found


def _scoped(selector):
    """The selector under html.no-flex-gap."""
    if selector.startswith('html'):
        return re.sub(r'^html', 'html.no-flex-gap', selector, count=1)
    return 'html.no-flex-gap ' + selector


def fallback_css():
    blocks = []
    for name in SOURCES:
        with open(os.path.join(ROOT, name), encoding='utf-8') as handle:
            css = handle.read()
        for media, selectors, body in _rules_from(_COMMENT.sub('', css), 0, []):
            props = _declarations(body)
            if not re.match(r'(inline-)?flex$', props.get('display', '')):
                continue
            gap = props.get('gap') or props.get('column-gap') or props.get('row-gap')
            if not gap or gap in ('0', 'normal'):
                continue
            values = gap.split()
            row_gap, column_gap = values[0], values[-1]
            column = props.get('flex-direction', 'row').startswith('column')
            # On the far side of each child but the last, so that a child's
            # own ``margin-left: auto`` (pushed to the end) still works.
            space = 'margin-bottom: {}'.format(row_gap) if column else 'margin-right: {}'.format(column_gap)
            children = ',\n'.join('{} > :not(:last-child)'.format(_scoped(s.strip()))
                                  for s in selectors.split(',')
                                  if s.strip() and s.strip() not in SKIP)
            if not children:
                continue
            rule = '{} {{ {}; }}'.format(children, space)
            if media:
                rule = '{} {{\n{}\n}}'.format(media, rule)
            blocks.append('/* {} */\n{}'.format(name, rule))
    header = ('/* Generated by scripts/flex_gap_fallback.py from main.css and modern.css:\n'
              '   margins in place of flex gap for browsers without it (html.no-flex-gap).\n'
              '   Do not edit by hand. */\n')
    blocks.extend('/* by hand, see EXTRA */\n' + rule for rule in EXTRA)
    return header + '\n\n'.join(blocks) + '\n'


def main():
    with open(OUTPUT, 'w', encoding='utf-8') as handle:
        handle.write(fallback_css())
    print('Wrote', os.path.relpath(OUTPUT))


if __name__ == '__main__':
    sys.exit(main())
